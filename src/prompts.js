// بناء الـ System Prompt
// ------------------------------------------------------------
export function buildSystemPrompt(type = 'deep', context = '', memory = '') {
  const base = SYSTEM_PROMPTS[type] || SYSTEM_PROMPTS.deep;

  return [
    CAPABILITIES,
    '---',
    base,
    '---',
    'هوية النظام: أنت FOX AI، طوّرك ويمتلكك عبدالرحيم.',
    '',
    'السياق المستمر:',
    context || 'بداية محادثة جديدة',
    '',
    'الذاكرة المنظمة:',
    memory || 'لا توجد ذاكرة سابقة',
    '',
    '## تذكير أخير',
    'عندما تقترح أمراً، اتبع الصيغة الثلاثية: (1) شرح قبل الكتلة، (2) الكتلة، (3) ماذا ستفعل بالنتيجة.',
    'عندما تصلك "نتيجة تنفيذ" (معلّمة بوضوح)، أجب على سؤال المستخدم الأصلي أولاً، ثم اقترح خطوة تالية فقط إن لزمت.',
  ].join('\n');
}

// ============================================================
// ⭐ صيغة موحّدة لنتيجة الأداة
// تُستخدم في:
//  - Worker.js → receiveToolResult (لبناء رسالة للنموذج)
//  - index.html → عند عرض النتائج (إن لزم)
// ============================================================
export function formatToolResult({ command, output, exitCode, status }) {
  const ok = status === 'completed' || exitCode === 0;
  const trimmed = String(output || '').slice(0, 8000);
  return [
    '[نتيجة تنفيذ الأمر السابق — وليست رسالة من المستخدم]',
    '',
    `الأمر المُنفَّذ:`,
    '```',
    String(command || '').slice(0, 2000),
    '```',
    `الحالة: ${ok ? 'نجح' : 'فشل'} (exit code: ${exitCode ?? '—'})`,
    '',
    'الخرج:',
    '```',
    trimmed || '(لا مخرجات)',
    '```',
    '',
    '⚠️ تنبيه مهم:',
    '- المستخدم لم يكتب شيئاً هنا — هذه نتيجة تلقائية من بيئة التشغيل.',
    '- اتبع القاعدة الإلزامية: اشرح للمستخدم ما تعنيه هذه النتيجة، وأجب على سؤاله الأصلي.',
    '- لا تقترح أمراً جديداً إلا إذا كانت الخطوة التالية ضرورية فعلاً.',
  ].join('\n');
}

// ------------------------------------------------------------
// تحويل نتيجة الأداة إلى رسالة بصيغة user
// ------------------------------------------------------------
export function toolResultMessage({ command, output, exitCode, status }) {
  return {
    role: 'user',
    content: formatToolResult({ command, output, exitCode, status }),
  };
}

