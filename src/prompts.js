// صيغة موحّدة لنتيجة الأداة
// ============================================================
export function formatToolResult({ command, output, exitCode, status, mode }) {
  const ok = status === 'completed' || exitCode === 0;
  const trimmed = String(output || '').slice(0, 8000);

  const header = mode === 'autopilot'
    ? '[نتيجة تنفيذ تلقائي — وضع Auto-pilot نشط]'
    : '[نتيجة تنفيذ الأمر السابق — وليست رسالة من المستخدم]';

  const tail = mode === 'autopilot'
    ? [
        '⚠️ تنبيه:',
        '- المستخدم لم يكتب شيئاً — هذه نتيجة تلقائية.',
        '- إن نجح: انتقل للخطوة التالية مباشرة.',
        '- إن فشل: عدّل الأمر وأخرجه في نفس الرد.',
        '- لا تُكرّر نفس الأمر.',
      ]
    : [
        '⚠️ تنبيه مهم:',
        '- المستخدم لم يكتب شيئاً هنا — هذه نتيجة تلقائية من بيئة التشغيل.',
        '- اتبع القاعدة الإلزامية: اشرح للمستخدم ما تعنيه هذه النتيجة، وأجب على سؤاله الأصلي.',
        '- لا تقترح أمراً جديداً إلا إذا كانت الخطوة التالية ضرورية فعلاً.',
      ];

  return [
    header,
    '',
    `الأمر المُنفَّذ:`,
    '```',
    String(command || '').slice(0, 2000),
    '```',
    `الحالة: ${ok ? 'نجح' : 'فشل'} (exit code: ${exitCode ?? '—'})`,
    '',
    'الخرج:',
    '```',
    trimmed || '(لا مخرجات)',
    '```',
    '',
    ...tail,
  ].join('\n');
}

export function toolResultMessage({ command, output, exitCode, status, mode = 'normal' }) {
  return {
    role: 'user',
    content: formatToolResult({ command, output, exitCode, status, mode }),
  };
}

